pub fn code_const_name(i: u16) -> &'static str {
    CODE_CONST.get(i as usize).copied().unwrap_or("?")
}

/// The code constant index of a name (`CONST_SRC_CODE_` dropped).
pub fn code_const(name: &str) -> Option<u16> {
    CODE_CONST.iter().position(|n| *n == name).map(|i| i as u16)
}

pub fn code_texture_name(i: u32) -> &'static str {
    CODE_TEXTURE.get(i as usize).copied().unwrap_or("?")
}
